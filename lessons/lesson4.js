// relational or comparison operators

// > -  More than
// < - Less than
// >= - More than or equal to
// <= - Less than or equal to

var result = 6 <= 5;
console.log(result);


//equality operators

var x = 1
console.log(x == 1); //lose comparison. value in the left is equal to the value in the right
console.log(x === '1'); //strict comparison. data type and value in the left is equal to the data type and value in the right
